"""Optimizer harnesses: coding-agent programs that carry out one task non-interactively inside a directory
(read files, edit code, run shell commands) and then exit.

    codex  OpenAI Codex CLI          `codex exec -C <dir> "<task>"`
    dsh    DeepSeek Harness          `dsh --profile headless "<task>"`   (run with cwd=<dir>)

A harness is only the agent program; the model it drives is configured the same way for both, in aflow.toml:

    optimizer = "<provider>/<model>"   that provider from [providers] (address + key env var), like the executor
    optimizer = "<model>"              the harness's own login / default provider, with this model
    optimizer = ""                     the harness's own login and default model

Both run with full autonomy (no approval prompts, may write outside the directory), because the agent runs the
smoke-test command, which writes temporary files elsewhere.
"""
from __future__ import annotations

import os

from . import config

CODEX = os.environ.get("VFX_CODEX", "codex")
DSH = os.environ.get("VFX_DSH", "dsh")


class Harness:
    name = ""
    binary = ""

    def __init__(self, optimizer: str, effort: str, run_dir: str):
        self.spec, self.effort, self.run_dir = optimizer or "", effort, run_dir
        # "<provider>/<model>" -> a configured provider; a bare "<model>" -> the harness's own provider
        self.model = config.resolve(self.spec) if "/" in self.spec else None
        self.own_model = self.spec if self.spec and "/" not in self.spec else None

    def describe(self) -> str:
        return f"{self.name}（{self.spec or '自己的登录和默认模型'}）"

    def command(self, workdir: str, task: str) -> tuple[list[str], dict | None, str | None]:
        """-> (argv, env or None to inherit, cwd or None)."""
        raise NotImplementedError


class Codex(Harness):
    name, binary = "codex", CODEX

    def __init__(self, optimizer: str, effort: str, run_dir: str):
        super().__init__(optimizer, effort, run_dir)
        self.args = ["-c", f"model_reasoning_effort={effort}"]
        m = self.model
        if m:
            if not m.responses_api:
                raise ValueError(
                    f"codex 只能驱动提供 OpenAI Responses 接口的服务商，{m.provider!r} 没有这个接口。"
                    f"换成 harness = \"dsh\"；如果它其实支持，在 [providers.{m.provider}] 里加 responses_api = true")
            p = "model_providers.aflow"
            self.args += ["-c", "model_provider=aflow", "-c", f"{p}.name={m.provider}",
                          "-c", f"{p}.base_url={m.base_urls[0]}", "-c", f"{p}.wire_api=responses"]
            if m.api_key_env:
                self.args += ["-c", f"{p}.env_key={m.api_key_env}"]
            self.args += ["-m", m.model]
        elif self.own_model:
            self.args += ["-m", self.own_model]

    def command(self, workdir, task):
        return [self.binary, "exec", "--skip-git-repo-check", "-C", workdir, *self.args, task], None, None


class DSH(Harness):
    name, binary = "dsh", DSH
    # codex-style effort names -> DeepSeek effort levels (off / low / high / max)
    DEEPSEEK_EFFORT = {"minimal": "low", "low": "low", "medium": "high", "high": "high", "xhigh": "max", "max": "max"}

    def __init__(self, optimizer: str, effort: str, run_dir: str):
        super().__init__(optimizer, effort, run_dir)
        self.patch = f"{run_dir}/dsh.patch.yml"
        with open(self.patch, "w") as f:
            f.write(self.config_patch())

    def config_patch(self) -> str:
        """dsh config overlay for this run (`dsh --patch`): the model, and privacy (dsh uploads the session log
        to DeepSeek and asks an LLM for a session title by default; both are switched off)."""
        lines = ["# generated by vflowx.harness from aflow.toml",
                 "- id: session-log-deepseek", "  config:", "    enabled: false",
                 "- id: session-title-llm", "  disabled: true"]
        m, ds_effort = self.model, self.DEEPSEEK_EFFORT.get(self.effort, self.effort)
        if self.own_model or (m and m.kind == "deepseek"):        # dsh's built-in DeepSeek provider
            lines += ["- id: agent-default-model", "  config:", "    provider: deepseek-official",
                      f"    model: {self.own_model or m.model}", f"    reasoningEffort: {ds_effort}"]
        elif m:                                                   # any other provider from aflow.toml
            name = f"aflow-{m.provider}"
            # chat completions everywhere, except OpenAI: its reasoning models only take tools + reasoning together
            # on the Responses API
            api = "openai-responses" if m.kind == "openai" else "openai-completions"
            effort = (self.effort if self.effort in ("low", "medium", "high") else "high") if m.reasoning else "null"
            lines += ["- id: llm-pi-ai", "  config:", "    providers:", f"      {name}:",
                      f"        apiKeyEnv: {m.api_key_env or 'VFX_NO_KEY'}", f"        api: {api}",
                      f"        baseURL: {m.base_urls[0]}", "        models:", f"          - id: {m.model}"]
            if m.reasoning:
                lines += ["            reasoningEfforts: {low: low, medium: medium, high: high}"]
            lines += ["- id: agent-default-model", "  config:", f"    provider: {name}", f"    model: {m.model}",
                      f"    reasoningEffort: {effort}"]
        return "\n".join(lines) + "\n"

    def command(self, workdir, task):
        env = dict(os.environ)
        env.setdefault("DSH_PERMISSION_MODE", "danger-full-access")  # full autonomy, no approval prompts
        env.setdefault("DSH_TELEMETRY_MODE", "DISABLED")
        env.setdefault("NODE_USE_ENV_PROXY", "1")                    # Node's fetch honours HTTPS_PROXY
        env.setdefault("VFX_NO_KEY", "EMPTY")                        # key placeholder for keyless providers
        return [self.binary, "--profile", "headless", "--patch", self.patch, task], env, workdir


HARNESSES = {"codex": Codex, "dsh": DSH}


def make(harness: str, optimizer: str, effort: str, run_dir: str) -> Harness:
    if harness not in HARNESSES:
        raise ValueError(f"harness 只能是 {sorted(HARNESSES)}，收到 {harness!r}")
    return HARNESSES[harness](optimizer, effort, run_dir)
